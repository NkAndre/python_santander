b = 3

print(f'SOMA = ',a+b)

print(f'SUBTRAÇÃO = ',a-b)

print(f'MULTIPLICAÇÃO = ',a*b)

print(f'DIVISÃO = ',a/b)

print(f'DIVISÃO INTEIRA = ',a//b)

print(f'MODULO = ',a%b)

print(f'EXPONENCIAÇÃO = ',a**b)

